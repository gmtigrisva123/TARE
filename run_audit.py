"""Algorithm 1 of the paper, from the recordings to the audit.

The steps follow the numbered lines of Algorithm 1 in order. Nothing here
chooses a parameter; every value comes from `tare.config`, which holds
Table III.

The DIPSER frames are not redistributed, and no frame, landmark or rating is
generated by this script. It reads what is on disk and stops with an error
if something it needs is absent.

Usage:
    python run_audit.py --dipser-root PATH \
        --pose-task pose_landmarker.task \
        --face-task face_landmarker.task \
"""

import argparse
import json
import os
import pickle

import numpy as np

from tare import audit, config, dataset, features, landmarks, models, stats, zoom


def parse_args():
    parser = argparse.ArgumentParser(description="Run the TARE audit pipeline.")
    parser.add_argument("--dipser-root", required=True,
                        help="Root of the DIPSER release.")
    parser.add_argument("--pose-task",
                        help="Path to MediaPipe pose_landmarker.task. "
                             "Needed for every run except --survey, "
                             "--describe-only and --inspect-labels.")
    parser.add_argument("--face-task",
                        help="Path to MediaPipe face_landmarker.task.")
    parser.add_argument("--frame-glob", help="Override the frame pattern.")
    parser.add_argument("--rating-glob", help="Override the rating pattern.")
    parser.add_argument("--out-dir", default="outputs")
    parser.add_argument("--regressor", default="gb", choices=config.REGRESSORS)
    parser.add_argument("--cache", default="outputs/landmarks.pkl",
                        help="Where the extraction pass is cached.")
    parser.add_argument("--describe-only", action="store_true",
                        help="Report what the layout matches and stop.")
    parser.add_argument("--survey", action="store_true",
                        help="Walk the release and print the directory names "
                             "that are actually there, then stop. Run this "
                             "first; it guesses nothing.")
    parser.add_argument("--inspect-labels", action="store_true",
                        help="Print the structure of one label file and stop. "
                             "DIPSER stores five evaluations per student and "
                             "(1) averages the four experts only, so run this "
                             "before trusting the target.")
    parser.add_argument("--skip-image-zoom", action="store_true",
                        help="Leave out the branches that rerun the extractor "
                             "on warped images. Marks the run as partial.")
    return parser.parse_args()


def report_sessions(sessions, order):
    """Print what the sampling of III-E actually produced.

    The empty-bin count is worth seeing: those are the stretches where the
    camera dropped frames, which III-E says are flagged missing rather than
    filled from a neighbour.
    """
    rates = [i["images_per_second"] for i in sessions.values()]
    bins = sum(i["bins"] for i in sessions.values())
    empty = sum(i["empty_bins"] for i in sessions.values())
    unlabelled = sum(i["dropped_for_no_label"] for i in sessions.values())

    note = ("the camera rate; Table III says about "
            f"{config.NOMINAL_FRAME_RATE}") if max(rates) > 2 else (
        "the sampling rate, since this tree already holds only the "
        "sampled frames")
    print(f"  sessions {len(sessions)}, "
          f"{min(rates):.2f} to {max(rates):.2f} images per second, {note}")
    print(f"  bins {bins}, of which {empty} empty and left missing")
    if unlabelled:
        print(f"  {unlabelled} sampled frames had no rating at their second "
              "and are not scored")

    first = {activities[0] for activities in order.values()}
    print(f"  earliest session per student, used by (6): {sorted(first)}")


def read_image(path):
    import cv2

    image = cv2.imread(path, cv2.IMREAD_COLOR)
    if image is None:
        raise FileNotFoundError(f"Could not read frame {path}.")
    return cv2.cvtColor(image, cv2.COLOR_BGR2RGB)


def extract_all(frames, extractor, cache_path):
    """Line 2 of Algorithm 1, run once and cached.

    One extraction feeds all three variants, which is what III-G requires.
    """
    if cache_path and os.path.exists(cache_path):
        with open(cache_path, "rb") as handle:
            cached = pickle.load(handle)
        if len(cached) == len(frames):
            for frame, lm in zip(frames, cached):
                frame.landmarks = lm
            print(f"Read cached landmarks for {len(frames)} frames.")
            return

    for n, frame in enumerate(frames, start=1):
        frame.landmarks = extractor(read_image(frame.image_path))
        if n % 500 == 0:
            print(f"  extracted {n}/{len(frames)} frames")

    if cache_path:
        os.makedirs(os.path.dirname(cache_path) or ".", exist_ok=True)
        with open(cache_path, "wb") as handle:
            pickle.dump([f.landmarks for f in frames], handle)


def run_clean_pipeline(frames, students, session_order, regressor_kind,
                       expert_ratings):
    """Lines 4 to 14: the three feature sets, the folds, ERROR, GAP and LEAK."""
    feature_sets, diagnostics = features.build_all(frames, session_order)

    results = {"variants": {}, "diagnostics": {
        "scale_branch_shares": diagnostics["branch_shares"],
        "students_without_baseline": [
            s for s, ok in diagnostics["has_baseline"].items() if not ok
        ],
        "detection_rate_by_activity": landmarks.detection_rate_by_activity(frames),
    }}

    predictions, frame_error, student_error = {}, {}, {}
    for variant in config.VARIANTS:
        predictions[variant] = models.out_of_fold_predictions(
            feature_sets[variant], frames, students, regressor_kind
        )
        frame_error[variant] = audit.frame_errors(predictions[variant], frames)
        student_error[variant] = audit.student_errors(
            frame_error[variant], frames, students
        )

    # Line 13: ERROR and the reference predictors.
    references = models.reference_predictors(frames, students, expert_ratings)
    results["references"] = {"B4": references["B4"]}
    for name in ("B1", "B2", "B3"):
        error = audit.frame_errors(references[name], frames)
        per_student = audit.student_errors(error, frames, students)
        results["references"][name] = audit.error_summary(per_student)

    for variant in config.VARIANTS:
        raw = student_error["RAW"] if variant != "RAW" else None
        results["variants"][variant] = {
            "error": audit.error_summary(student_error[variant], raw),
            "error_by_activity": audit.error_by_activity(
                frame_error[variant], frames, students
            ),
        }

    # Line 14: GAP and LEAK, for each proxy of (14).
    proxies = audit.apparent_scale_proxies(frames, students)
    results["proxies"] = proxies

    for proxy_name, proxy in proxies.items():
        groups = audit.scale_groups(proxy)
        results.setdefault("groups", {})[proxy_name] = groups

        for variant in config.VARIANTS:
            record = results["variants"][variant].setdefault(proxy_name, {})
            record["eo_reg"] = audit.equalized_odds_regression(
                frame_error[variant], frames, groups
            )
            record["eo_bin"] = {
                str(tau): audit.equalized_odds_binary(
                    predictions[variant], frames, groups, tau
                )
                for tau in (config.THRESHOLD,) + config.THRESHOLD_SENSITIVITY
            }
            record["rho"] = audit.rank_association(student_error[variant], proxy)
            record["rho_interval"] = audit.rank_association_interval(
                student_error[variant], proxy
            )
            record["leak"] = audit.leakage(feature_sets[variant], frames, proxy)

            # III-C9 lists (11) among the quantities that get a student bootstrap.
            record["eo_reg"]["interval"] = audit.gap_interval(
                frames, students,
                lambda rows, v=variant, g=groups: audit.equalized_odds_regression(
                    frame_error[v][rows], [frames[i] for i in rows], g
                )["gap"],
            )
            record["eo_bin"][str(config.THRESHOLD)]["interval"] = audit.gap_interval(
                frames, students,
                lambda rows, v=variant, g=groups: audit.equalized_odds_binary(
                    predictions[v][:, rows], [frames[i] for i in rows],
                    g, config.THRESHOLD
                )["gap"],
            )

            if variant != "RAW":
                raw_record = results["variants"]["RAW"][proxy_name]
                record["delta_eo_reg"] = audit.gap_change(
                    raw_record["eo_reg"]["gap"], record["eo_reg"]["gap"]
                )
                key = str(config.THRESHOLD)
                record["delta_eo_bin"] = audit.gap_change(
                    raw_record["eo_bin"][key]["gap"], record["eo_bin"][key]["gap"]
                )
                record["delta_rho"] = audit.association_change(
                    raw_record["rho"], record["rho"]
                )

    return results, feature_sets, predictions, frame_error, student_error


def run_inference(frames, students, student_error, frame_error, predictions,
                  proxies, results):
    """Line 20: bootstrap over students, sign-flip tests and Holm."""
    inference = {"bootstrap": {}, "sign_flip": {}, "equivalence": {}}
    p_values = {}

    for variant in ("TARE-S", "TARE-FULL"):
        gains = {
            s: student_error["RAW"][s] - student_error[variant][s] for s in students
        }

        def mean_gain(resample, gains=gains):
            return float(np.nanmean([gains[s] for s in resample]))

        interval = stats.bootstrap_students(
            students, mean_gain, level=config.EQUIVALENCE_LEVEL
        )
        inference["bootstrap"][f"{variant}:mean_delta"] = {
            k: v for k, v in interval.items() if k != "draws"
        }
        inference["equivalence"][variant] = stats.equivalence(interval)

        test = stats.sign_flip_test(list(gains.values()))
        inference["sign_flip"][variant] = test
        p_values[f"{variant}:ERROR"] = test["p_value"]

        for proxy_name, proxy in proxies.items():
            groups = audit.scale_groups(proxy)
            for form, label in (("eo_reg", "EO_reg"),
                                ("eo_bin", f"EO_bin({config.THRESHOLD})")):
                def gap_delta(resample, form=form, groups=groups, variant=variant):
                    return _resampled_gap_change(
                        resample, frames, frame_error, predictions, groups, form, variant
                    )

                draws = stats.bootstrap_students(students, gap_delta)
                inference["bootstrap"][f"{variant}:{label}:{proxy_name}"] = {
                    k: v for k, v in draws.items() if k != "draws"
                }
                p_values[f"{variant}:{label}:{proxy_name}"] = stats.gap_change_p_value(
                    draws.get("draws", [])
                )

    inference["holm"] = stats.holm(p_values)
    inference["primary_family"] = stats.primary_family_names()
    results["inference"] = inference
    return results


def _resampled_gap_change(resample, frames, frame_error, predictions, groups,
                          form, variant):
    """Delta_EO on a bootstrap resample of students.

    The group of a student travels with the student, which is what III-C9
    asks for. A resample draws students with replacement, so a student's
    frames are repeated as often as the student is.
    """
    counts = {}
    for student in resample:
        counts[student] = counts.get(student, 0) + 1
    rows = []
    for idx, frame in enumerate(frames):
        rows.extend([idx] * counts.get(frame.student, 0))
    if not rows:
        return float("nan")

    import copy

    subset = [copy.copy(frames[i]) for i in rows]
    if form == "eo_reg":
        raw = audit.equalized_odds_regression(frame_error["RAW"][rows], subset, groups)
        new = audit.equalized_odds_regression(frame_error[variant][rows], subset, groups)
    else:
        raw = audit.equalized_odds_binary(
            predictions["RAW"][:, rows], subset, groups, config.THRESHOLD
        )
        new = audit.equalized_odds_binary(
            predictions[variant][:, rows], subset, groups, config.THRESHOLD
        )
    return audit.gap_change(raw["gap"], new["gap"])


def main():
    args = parse_args()
    os.makedirs(args.out_dir, exist_ok=True)

    layout = config.DipserLayout(root=args.dipser_root)
    if args.frame_glob:
        layout.frame_glob = args.frame_glob
    if args.rating_glob:
        layout.rating_glob = args.rating_glob

    if args.survey:
        dataset.survey(args.dipser_root)
        return

    if args.describe_only:
        report = dataset.describe_layout(layout)
        if not report:
            print("Nothing matched. Check --dipser-root and --frame-glob.")
            print(f"  root:       {layout.root}")
            print(f"  frame_glob: {layout.frame_glob}")
            return
        for (student, activity) in sorted(report):
            counts = report[(student, activity)]
            print(f"student {student} activity {activity}: "
                  f"{counts['frames']} frames, "
                  f"{counts['rating_files']} rating files")
        students = sorted({s for s, _ in report})
        print(f"{len(students)} students matched; assumption A6 names 16.")
        return

    if args.inspect_labels:
        dataset.inspect_labels(layout)
        return

    # Lines 1 and 3: sampling and the target. The session order comes back
    # with the frames, because both are read from the image timestamps.
    students, frames, order, sessions = dataset.load_cohort(layout)
    print(f"{len(students)} students, {len(frames)} scored frames.")
    if len(students) != 16:
        print(f"Note: assumption A6 names 16 students and the layout gave "
              f"{len(students)}. Check the layout before reading the numbers.")
    report_sessions(sessions, order)

    starts = {key: info["start_clock"] for key, info in sessions.items()}
    horizons = {key: info["last_second"] for key, info in sessions.items()}
    expert_ratings = dataset.expert_rating_table(
        layout, students, starts, horizons
    )

    # Line 2.
    if not (args.pose_task and args.face_task):
        raise SystemExit(
            "--pose-task and --face-task are required for a full run. "
            "Download pose_landmarker.task and face_landmarker.task from the "
            "MediaPipe model index."
        )
    extractor = landmarks.LandmarkExtractor(args.pose_task, args.face_task)
    extract_all(frames, extractor, args.cache)

    # Lines 4 to 14.
    results, feature_sets, predictions, frame_error, student_error = run_clean_pipeline(
        frames, students, order, args.regressor, expert_ratings
    )
    results["run"] = {
        "regressor": args.regressor,
        "n_students": len(students),
        "n_frames": len(frames),
        "complete": not args.skip_image_zoom,
    }

    # Line 15: ZOOM at the keypoint level, the unit test of Remark 3.
    results["zoom_keypoint"] = _serialise_zoom(
        zoom.keypoint_level_drift(frames, students, order, args.regressor)
    )

    if not args.skip_image_zoom:
        # Line 16.
        results["zoom_image"] = _serialise_zoom(
            zoom.image_level_drift(
                frames, students, order, args.regressor, extractor, read_image
            )
        )
        # Lines 17 to 19.
        curve = zoom.dose_response(
            frames, students, order, args.regressor, extractor, read_image
        )
        results["dose_response"] = {"curve": curve["curve"], "fit": curve["fit"]}
        cohort = zoom.perturbed_cohort(
            frames, students, order, args.regressor, extractor, read_image,
            results["proxies"],
        )
        # The distribution over b is what III-C8 reports; the per-replicate
        # student errors stay out of the JSON to keep it readable.
        results["perturbed_cohort"] = cohort["distribution"]
        results["perturbed_cohort_factors"] = [
            r["factors"] for r in cohort["replicates"]
        ]
    else:
        print("Image-level ZOOM and per-student scaling were skipped. "
              "This run does not cover RQ3.")

    # Line 20.
    results = run_inference(
        frames, students, student_error, frame_error, predictions,
        results["proxies"], results
    )

    path = os.path.join(args.out_dir, f"audit_{args.regressor}.json")
    with open(path, "w") as handle:
        json.dump(_stringify_keys(results), handle, indent=2, default=_jsonable)
    print(f"Wrote {path}")


def _serialise_zoom(table):
    out = {}
    for (variant, c, delta), value in table.items():
        out.setdefault(variant, {})[f"c={c:.4f},delta={delta:+.0f}"] = value
    return out


def _stringify_keys(obj):
    """Make a structure writable as JSON.

    The equalized-odds tables are keyed by the (label class, group) cell, and
    JSON only takes string keys, so a tuple key becomes its parts joined by a
    bar: the cell (3, 1) is written "3|1". Everything else is left alone.
    """
    if isinstance(obj, dict):
        out = {}
        for key, value in obj.items():
            if isinstance(key, tuple):
                key = "|".join(str(part) for part in key)
            elif not isinstance(key, (str, int, float, bool)) and key is not None:
                key = str(key)
            out[key] = _stringify_keys(value)
        return out
    if isinstance(obj, (list, tuple)):
        return [_stringify_keys(item) for item in obj]
    return obj


def _jsonable(obj):
    if isinstance(obj, (np.floating, np.integer)):
        return obj.item()
    if isinstance(obj, np.ndarray):
        return obj.tolist()
    if isinstance(obj, set):
        return sorted(obj)
    if isinstance(obj, tuple):
        return list(obj)
    return str(obj)


if __name__ == "__main__":
    main()
